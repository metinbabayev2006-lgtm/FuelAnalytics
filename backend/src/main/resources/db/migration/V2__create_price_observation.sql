CREATE TABLE price_observation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    station_id UUID NOT NULL REFERENCES station (id),
    fuel_type VARCHAR(6) NOT NULL CHECK (fuel_type IN ('diesel', 'e5', 'e10')),
    price NUMERIC(6, 3) NOT NULL CHECK (price > 0),
    observed_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_price_observation UNIQUE (station_id, fuel_type, observed_at)
);

-- Supports station/fuel histories and prevents duplicate observations per instant.
-- observed_at is our collection time, not the provider's price-change time.
